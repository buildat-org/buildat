local function emit(path, text)
	local f = io.open(path, "rb")
	local old = f and f:read("*a")
	if f then f:close() end
	if old == text then
		return true
	end
	if CHECK then
		io.stderr:write(path.." is not what util/gen_wasm_bindings.lua writes; "..
				"run it again\n")
		return false
	end
	f = assert(io.open(path, "wb"))
	f:write(text)
	f:close()
	print("wrote "..path)
	return true
end
