			const unsigned int at = 12 + (unsigned int)len;
			detail::Reply r((int)(e.size - at), detail::g_event + at, e.size - at);
			while(r.left() && e.fields < BUILDAT_EVENT_FIELDS_MAX)
				e.field[e.fields++] = r.value();
		}
	}
	return true;
}
