-- Draws voxelworld's chunks with PBRVoxel, the shader and technique in this
-- module's client_data. The mesher sets no technique of its own; it hands a
-- shader an atlas, a normal map, a surface map and a skylight value per vertex,
-- and interface/mesh.h says in what. Everything here is what a game could do
-- for itself: a module has no privileges a game lacks, it can just be shared.
--
-- A game needs:
--   zone.zoneTexture = magic.cache:GetResource("TextureCube", M.sky_cubemap)
--   voxel_shading.create_skybox(scene, sun_dir)
--   voxel_shading.set_camera(camera_node)
--   voxel_shading.update(dt) every frame, or update(nil) to snap
--   voxel_shading.apply_to_node(node) for voxel geometry of its own
-- and voxelworld.use_skylight set, which is what fills the vertex colors.
local log = buildat.Logger("voxel_shading")
local magic = require("buildat/extension/urho3d")
local voxelworld = require("buildat/module/voxelworld")

local M = {}

-- The sky the shader reflects, generated by
-- apps/sample_lighting_scene/make_client_data.py. Where the sky cannot be seen the
-- shader dims this one by direction rather than reflecting a second, indoor
-- cube map; see the sky visibility note below.
M.sky_cubemap = "voxel_shading/VoxelSky.xml"

local TECHNIQUE = magic.cache:GetResource("Technique",
		"voxel_shading/PBRVoxel.xml")
-- The same shader reading the voxel format's surface modifiers out of the
-- vertex tangent; see PBRVoxelModifiers.xml. A world that binds no modifier
-- has nothing in the tangent, so this is opt-in.
local TECHNIQUE_MODIFIERS = magic.cache:GetResource("Technique",
		"voxel_shading/PBRVoxelModifiers.xml")
-- For the faces the mesher put on a chunk's "alpha" child: the same shader
-- blended rather than cut out. See PBRVoxelAlpha.xml.
local TECHNIQUE_ALPHA = magic.cache:GetResource("Technique",
		"voxel_shading/PBRVoxelAlpha.xml")
-- And for the faces on its "masked" child: the same shader again, cut out by
-- the texture's own alpha rather than drawn through it. See
-- PBRVoxelMasked.xml.
local TECHNIQUE_MASKED = magic.cache:GetResource("Technique",
		"voxel_shading/PBRVoxelMasked.xml")

-- The same three with the sun gated by the skylight in the vertex colors: a
-- surface the sky cannot reach gets no direct sunlight. A world whose light
-- value means "how much sky is here" wants this; see use_sun_gate().
local TECHNIQUE_SUN = magic.cache:GetResource("Technique",
		"voxel_shading/PBRVoxelSun.xml")
local TECHNIQUE_SUN_MODIFIERS = magic.cache:GetResource("Technique",
		"voxel_shading/PBRVoxelSunModifiers.xml")
local TECHNIQUE_SUN_ALPHA = magic.cache:GetResource("Technique",
		"voxel_shading/PBRVoxelSunAlpha.xml")
local TECHNIQUE_SUN_MASKED = magic.cache:GetResource("Technique",
		"voxel_shading/PBRVoxelSunMasked.xml")

-- The eight above, in one table, so that a game can hand over eight of its
-- own instead. **Nothing about the look changes for a game that does not**:
-- these are the same resources, under the same names, and apply_to_node()
-- reads them from here.
--
-- What wants that is builtin/luanti, which is hosting Luanti and wants
-- Luanti's look where the other nine games using this module want buildat's.
-- One shader set for both Luanti clients lives in
-- extensions/luanti_client/res/; see [SHADER_HOME] in
-- doc/plan/master_plan.md for why there and not here.
local techniques = {
	plain = TECHNIQUE,
	modifiers = TECHNIQUE_MODIFIERS,
	alpha = TECHNIQUE_ALPHA,
	masked = TECHNIQUE_MASKED,
	sun = TECHNIQUE_SUN,
	sun_modifiers = TECHNIQUE_SUN_MODIFIERS,
	sun_alpha = TECHNIQUE_SUN_ALPHA,
	sun_masked = TECHNIQUE_SUN_MASKED,
}

-- Draw with somebody else's techniques: a table of resource names under the
-- keys above, any of which may be left out to keep this module's own. Set it
-- before the first chunk arrives; what is already drawn keeps the technique
-- it was given, which is what use_sun_gate() says too.
--
-- The shader behind them is theirs as well, so what this module still owns
-- for such a game is the *choosing* -- which of the eight a chunk, its
-- translucent child and its masked child get -- and the parameters
-- update() pushes.
function M.use_technique_set(names)
	if type(names) ~= "table" then
		return
	end
	for key, name in pairs(names) do
		if techniques[key] == nil then
			log:warning("use_technique_set: no technique called " ..
					tostring(key))
		else
			local res = magic.cache:GetResource("Technique", name)
			if res == nil then
				log:warning("use_technique_set: no resource " ..
						tostring(name))
			else
				techniques[key] = res
			end
		end
	end
end

local sun_gate = false
local use_modifiers = false

-- How much of the sky the camera can see, per direction: the cube the
-- shader multiplies the sky cube map by, which is the whole indoor/outdoor
-- treatment. It is extensions/voxel_light's ray cube ([LC_SKY_SHARED]),
-- served by this module's server (client_extensions in meta.json) so it is
-- the version the served shaders know; the voxels it marches through are
-- collected here.
local ok_vl, err_vl, voxel_light =
		buildat.run_script_file("voxel_light/init.lua")
if not ok_vl or type(voxel_light) ~= "table" then
	error("voxel_shading: could not load voxel_light: " .. tostring(err_vl))
end
M.voxel_light = voxel_light
-- Chunks are collected around the camera out to the reach of a ray, and the
-- list is kept until the camera crosses into another chunk: which chunks are
-- within reach does not change until then. Rebuilt every so many sweeps as
-- well, since a streaming world loads chunks under a camera that is standing
-- still.
local VOLUME_MARGIN = voxel_light.RAY_VOXELS
local VOLUME_REFRESH_SWEEPS = 20

local camera_node = nil
-- Which chunk the collected volumes are for, and how many sweeps ago
local volumes_chunk_x, volumes_chunk_y, volumes_chunk_z = nil, nil, nil
local volumes_age = VOLUME_REFRESH_SWEEPS
-- What collect_volumes() hands voxel_light, reused
local collected = {volumes = {}}
-- The scene passes' parameters, which voxel_light keeps on the render
-- path with its own, and what each is until a game sets it:
--   SpecEmphasis     multiplies the reflected sky; 1 is what a game renders,
--                    the benchmarks turn it up (M.set_specular_emphasis())
--   SkyLight         how much light is on the sky the reflections come from
--                    (M.set_sky_light())
--   SkyTint, SkyTintAmount  and what colour it is now, against the noon sky
--                    the cube map holds; white and none is the cube map as
--                    baked (M.set_sky_tint())
--   BounceLight      light off the surroundings, where the sky does not
--                    reach (M.set_bounce_light())
--   GroundLight      the ground's radiance, for the lower hemisphere
--                    (M.set_ground_light())
--   LampLight        a lamp at full on the packed path, in the ambient's
--                    units (M.set_lamp_light()); white is the plain path's
--   CaveAmbient      [CAVE_AO]: what a cave is never darker than, the same
--                    at every hour; nothing until a client sets it
--   ChamberLight, GrayByLight, TranslucencyGain  see their setters
--   ProbeBox         off for a world with a sky: a cube map at infinity
--                    wants no parallax ([LAUNCH_WORLD]'s room is the one
--                    that does)
local vis_params = {
	SpecEmphasis = 1.0,
	SkyLight = 1.0,
	SkyTint = magic.Vector3(1, 1, 1),
	SkyTintAmount = 0.0,
	BounceLight = magic.Vector3(0, 0, 0),
	GroundLight = magic.Vector3(0, 0, 0),
	LampLight = magic.Vector3(1, 1, 1),
	CaveAmbient = magic.Vector3(0, 0, 0),
	ChamberLight = 1.0,
	GrayByLight = 0.0,
	TranslucencyGain = 1.0,
	ProbeBox = 0.0,
}
local vis = nil -- voxel_light's, made once collect_volumes() is
-- Whether the mesher packs the vertex alpha; see M.set_packed_sky()
local packed_sky = 0.0
-- The shadow-kind diagnostic; see M.set_shadow_kinds()
local shadow_kinds = 0.0

local function each_material_of(cg, cb)
	if not cg then return end
	local i = 0
	while true do
		local m = cg:GetMaterial(i)
		if m == nil then break end
		cb(m)
		i = i + 1
	end
end

local function each_material(node, cb)
	each_material_of(node:GetComponent("CustomGeometry"), cb)
end

-- Draw a node's voxel geometry with this module's shader. Called for every
-- chunk voxelworld meshes; a game with voxel geometry of its own outside the
-- voxel world -- a rigid body made of voxels, say -- calls it for that node so
-- that the two are lit the same way. Such a node has no skylight in its vertex
-- data, and the shader then sees full skylight, which is what an object out in
-- the open should get.
function M.apply_to_node(node)
	local technique
	if sun_gate then
		technique = use_modifiers and techniques.sun_modifiers or
				techniques.sun
	else
		technique = use_modifiers and techniques.modifiers or techniques.plain
	end
	each_material(node, function(m)
		m:SetTechnique(0, technique)
		m:SetShaderParameter("PackedSky", packed_sky)
		m:SetShaderParameter("ShadowKinds", shadow_kinds)
		-- **A parameter a material never sets is not zero** ([LOOK_CHECK]
		-- says so, and 2026-09-24 paid for it): the parallax correction
		-- [LAUNCH_WORLD] wants for a cube map that holds a room -- rather
		-- than a sky, which is at infinity and needs none -- is off for a
		-- world with a sky, and saying so here is what keeps it off.
		-- Without this line sample_lighting_scene's pond and cave mouths moved
		-- by ten times their own run-to-run noise.
		m:SetShaderParameter("ProbeBox", 0.0)
	end)
	-- The faces of the world's translucent voxels, which the mesher puts on a
	-- child node of their own so that Urho3D sorts them against the other
	-- chunks' translucent geometry rather than against the opaque geometry
	-- they are mixed with. Without a technique they are invisible rather than
	-- see-through, so a world with water in it needs this whether or not it
	-- knows about the child.
	local alpha_node = node:GetChild("alpha")
	if alpha_node then
		each_material_of(alpha_node:GetComponent("CustomGeometry"),
				function(m)
			m:SetTechnique(0, sun_gate and techniques.sun_alpha or
					techniques.alpha)
			m:SetShaderParameter("PackedSky", packed_sky)
			m:SetShaderParameter("ShadowKinds", shadow_kinds)
			m:SetShaderParameter("ProbeBox", 0.0)
		end)
	end
	-- And the alpha-masked ones, which are solid world with the holes in
	-- their textures cut out. A game that marks no voxel masked never has
	-- this child.
	local masked_node = node:GetChild("masked")
	if masked_node then
		each_material_of(masked_node:GetComponent("CustomGeometry"),
				function(m)
			m:SetTechnique(0, sun_gate and techniques.sun_masked or
					techniques.masked)
			m:SetShaderParameter("PackedSky", packed_sky)
			m:SetShaderParameter("ShadowKinds", shadow_kinds)
			m:SetShaderParameter("ProbeBox", 0.0)
		end)
	end
end

-- Whether the sun is gated by the skylight the mesher packed into the vertex
-- colours. A shadow map cannot tell a cave from a canopy -- in both the sky
-- is blocked by geometry that is being drawn -- so the world's own light
-- value is what says whether the sun reaches a surface at all. Turn it on in
-- a world that maintains voxelworld's skylight, and leave it off in one that
-- does not: there every surface reads as underground and the sun never
-- arrives. Set it before the first chunk arrives; what is already drawn
-- keeps the technique it was given.
function M.use_sun_gate(enable)
	sun_gate = enable and true or false
end

-- Read the voxel format's surface modifiers, for a world whose format binds
-- any. Set it before the first chunk arrives; what is already drawn keeps the
-- technique it was given.
function M.use_modifiers(enable)
	use_modifiers = enable and true or false
end

voxelworld.sub_material_update(M.apply_to_node)

-- The chunks a ray could reach, for voxel_light. The engine picks the one it
-- needs per step out of this list, so it only has to be the right set, not
-- a short one.
--
-- Rebuilding it every sweep cost half a millisecond a frame, which was more
-- than the rays; it is the same set until the camera changes chunk.
local function collect_volumes(origin)
	local cs = voxelworld.chunk_size_voxels
	if cs == nil then
		return nil -- voxelworld is not initialized yet
	end
	local cx = math.floor(origin.x / cs.x)
	local cy = math.floor(origin.y / cs.y)
	local cz = math.floor(origin.z / cs.z)
	-- An empty list is not kept: that is a world still loading, and it will
	-- have chunks in a moment
	volumes_age = volumes_age + 1
	if volumes_age < VOLUME_REFRESH_SWEEPS and cx == volumes_chunk_x and
			cy == volumes_chunk_y and cz == volumes_chunk_z and
			collected.volumes[1] ~= nil then
		return collected
	end
	volumes_chunk_x, volumes_chunk_y, volumes_chunk_z = cx, cy, cz
	volumes_age = 0
	local volumes = collected.volumes
	for i = #volumes, 1, -1 do
		volumes[i] = nil
	end
	local n = 0
	for z = math.floor((origin.z - VOLUME_MARGIN) / cs.z),
			math.floor((origin.z + VOLUME_MARGIN) / cs.z) do
		for y = math.floor((origin.y - VOLUME_MARGIN) / cs.y),
				math.floor((origin.y + VOLUME_MARGIN) / cs.y) do
			for x = math.floor((origin.x - VOLUME_MARGIN) / cs.x),
					math.floor((origin.x + VOLUME_MARGIN) / cs.x) do
				local node = voxelworld.get_static_node(
						buildat.Vector3(x, y, z))
				local volume = node and voxelworld.get_volume(node) or nil
				if volume ~= nil then
					n = n + 1
					volumes[n] = {x = x, y = y, z = z, volume = volume}
				end
			end
		end
	end
	collected.chunk_size = cs
	collected.registry = voxelworld.get_voxel_registry()
	return collected
end

vis = voxel_light.new_vis(magic, buildat, collect_volumes, vis_params)


-- **A field over the world** ([SKELENTI_DANGER_LOOK]): a value 0 to 1 per
-- cell of a grid on x and z that a game sets -- skelenti's danger -- and
-- the shader reads at each pixel, filtered between the cells. A texture
-- on unit 6 of the scene and light passes, as the parameters above are,
-- and AreaField the grid's corner and size: (x0, z0, 1 / width, 1 /
-- depth) in nodes. What the shader makes of the value is the shader's;
-- zero everywhere, and before any field is set, is the plain look.
local AREA_FIELD_UNIT = 6
local area_field = nil -- {tex, name = its resource, param = Color}

-- set_area_field(x0, z0, cell, w, h, bytes): w * h bytes, row by row from
-- (x0, z0) along +x, each the value at a cell's middle times 255; nil
-- clears it
function M.set_area_field(x0, z0, cell, w, h, bytes)
	if x0 == nil then
		if area_field then
			area_field.param = magic.Color(0, 0, 0, 0)
		end
		vis:redeclare()
		return
	end
	assert(type(bytes) == "string" and #bytes == w * h,
			"set_area_field: w * h bytes")
	local img = magic.Image:new()
	img:SetSize(w, h, 1)
	magic.image_set_data(img, w, h, 1, bytes)
	-- One texture, filled again: the commands find it by its name
	if area_field == nil then
		local tex = magic.Texture2D:new()
		tex:SetNumLevels(1)
		magic.cache:AddManualResource(tex, "voxel_shading/area_field")
		area_field = {tex = tex, name = "generated/voxel_shading/area_field"}
	end
	area_field.tex:SetData(img)
	area_field.param = magic.Color(x0, z0, 1 / (w * cell), 1 / (h * cell))
	vis:redeclare()
end

local function push_area_field(render_path)
	for i = 0, render_path:GetNumCommands() - 1 do
		local command = render_path:GetCommand(i)
		if command ~= nil and (command.type == magic.CMD_SCENEPASS or
				command.type == magic.CMD_FORWARDLIGHTS) then
			command:SetTextureName(AREA_FIELD_UNIT, area_field.name)
			command:SetShaderParameter("AreaField", area_field.param)
		end
	end
end

vis.on_declare = function(render_path)
	if area_field then
		push_area_field(render_path)
	end
end

-- How much of the sky is visible overhead: 1 out in the open, towards 0
-- underground (the +Y face; [CAVE_SKY]). What wants it is whatever is not
-- per direction -- a zone's fog colour is the one.
function M.sky_visibility_above()
	return vis:above()
end

-- The whole cube's mean, and its lowest and highest cell
function M.sky_vis_stats()
	return vis:stats()
end

-- How lit the brightest air this chamber shows the camera is
-- ([UNDERGROUND_LIGHT]): the mean of the eight brightest cells
function M.chamber_light()
	return vis:chamber()
end

-- How much to multiply the reflected sky by, 1 being what a game renders.
--
-- For looking at what this module does rather than at the scene. Most of a
-- cave is rock reflecting almost nothing, so a change to the sampling that is
-- worth arguing about moves a wall by a fraction of a value out of 255 -- less
-- than PNG rounding, which makes screenshots useless as a way to tell whether
-- a change did anything. Turned up, the same change is tens of values and can
-- be measured. It scales the reflection alone, so what it exaggerates is
-- exactly what this module decides and nothing else.
-- How much light is on the sky a surface reflects: one is the daylight the
-- cube map was baked in, and a game with a clock turns it down as its night
-- comes. Without it a pond at midnight mirrors a bright blue sky.
-- Light bounced off the surroundings, in the zone ambient's units, which a
-- surface receives in proportion to how much sky it does not see: what
-- lights a cave by day. Nothing until a client sets it.
-- A lamp at full, in the ambient's units, for the packed path: the
-- mesher's lamp nibble is display white at full, which under a night
-- sky of 0.00005 and the meter drew a far ridge's lamp-lit snow white
-- ([PBR_FIT], [LOD_LIGHT]'s finding). The plain path keeps white.
-- The transmitted light's level through a translucent surface, over
-- Lambert through the leaf's colour squared ([PBR_FIT] 3b); the launcher
-- sets it from the fit, BUILDAT_VOXEL_TRANSLUCENCY overrides
function M.set_translucency_gain(k)
	vis:set_param("TranslucencyGain", math.max(0, k))
end

-- A light of the place rather than of the sky: a constant floor under the
-- ambient so that the corner table and the hemisphere rays still shape a
-- face where both nibbles are nought. Not scaled by the hour, which is
-- what keeps [DARK_INVARIANT] -- see cCaveAmbient in PBRVoxel.glsl.
-- [UNDERGROUND_LIGHT]: how lit the chamber the camera is in is, 0 to 1 and
-- above 1 to brighten a lit one. It scales the bounce term's floor in the
-- shader -- the light a face gets where the flood's nibble is nought -- so a
-- sealed place stops following the hour while a cave lit round a corner keeps
-- its light. One unless a client sets it, which is what the shader did before.
function M.set_chamber_light(f)
	vis:set_param("ChamberLight", math.max(0, f))
end

-- [NIGHT_GRAY]'s third ladder: show a face gray by the light it gets rather
-- than by the radiance it gives out -- gray at the cave floor's own level,
-- coloured a quarter above it. The frame pass does the same job on radiance
-- and cannot hold the rule across materials. Off unless a client asks.
-- top is the ramp's top as a multiple of the floor (1.25 is the picked
-- width); nil or false turns it off.
function M.set_gray_by_light(top)
	vis:set_param("GrayByLight",
			(type(top) == "number" and top > 0) and top or 0.0)
end

