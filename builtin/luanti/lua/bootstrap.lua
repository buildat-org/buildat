-- A content id here is a buildat VoxelRegistry id, not a number copied from
-- Luanti: the ids are allocated by whichever engine is running the game, and
-- here this module is that engine. devtest's own content_ids.lua only ever
-- asserts relations between them, never a literal.
--
-- So the three constants land where the registry already puts them:
-- VOXELTYPEID_UNDEFINED is 0 and means "nothing has generated this yet",
-- which is exactly ignore; add_voxel() then hands out 1, 2, 3... in the order
-- the definitions are built, which is content id order.
core.CONTENT_IGNORE = 0
core.CONTENT_UNKNOWN = 1
core.CONTENT_AIR = 2
reserve_content_id("ignore", core.CONTENT_IGNORE)
reserve_content_id("unknown", core.CONTENT_UNKNOWN)
reserve_content_id("air", core.CONTENT_AIR)
next_content_id = 3

function core.register_item_raw(def)
	local name = def.name
	if name == nil or name == "" then
		return
	end
	-- Only a node takes a content id; a craftitem or a tool is never in the
	-- world by itself
	if def.type == "node" and core.__content_ids[name] == nil then
		reserve_content_id(name)
	end
	-- Which ids a name list matches is kept; a new node may be in one of
	-- them. Registering after the mods have loaded is not normal, and this
	-- is what makes it harmless. See ids_and_names().
	if core.__forget_name_ids then
		core.__forget_name_ids()
	end
	return name
end

function core.unregister_item_raw(name)
	-- The id stays taken: a world already written in it does not stop
	-- meaning what it meant
	core.__aliases[name] = nil
	if core.__forget_craft_index then
		core.__forget_craft_index()
	end
end

function core.register_alias_raw(name, convert_to)
	core.__aliases[name] = convert_to
	-- What a recipe makes is looked up by its resolved name; see craft.lua
	if core.__forget_craft_index then
		core.__forget_craft_index()
	end
end

function core.get_content_id(name)
	if type(name) ~= "string" then
		error("get_content_id(): not a name: " .. tostring(name))
	end
	name = core.__aliases[name] or name
	local id = core.__content_ids[name]
	if id == nil then
		error("Unknown node: " .. tostring(name))
	end
	return id
end

-- What the importer asks for every name a Luanti world's blocks carry: the
-- id this run gave that node, through whatever alias the game registered,
-- and whether the game knows it at all. A name it does not know comes back
-- as "unknown", which is Luanti's own answer and is a node you can see and
-- dig rather than a hole in the world.
function core.__content_id_or_unknown(name)
	name = core.__aliases[name] or name
	local id = core.__content_ids[name]
	if id ~= nil then
		return id, true
	end
	return core.__content_ids["unknown"] or 0, false
end

function core.get_name_from_content_id(id)
	if type(id) ~= "number" then
		error("get_name_from_content_id(): not a content id: " .. tostring(id))
	end
	return core.__content_names[id] or "unknown"
end

-- Every node that has an id, from 1 upwards, flattened to what the module's
-- C++ needs to build a VoxelDefinition. Called once, after the mods have
-- loaded: add_voxel() takes a finished definition and hands out ids in call
-- order, so the definitions have to be built in one pass in id order, and
-- doing it at the end is also what makes core.override_item and
-- core.unregister_item non-issues -- only the final registered_nodes is ever
-- looked at.
--
-- Id 0 is ignore, which is VOXELTYPEID_UNDEFINED and has no definition.
-- Luanti's tiles are +Y, -Y, +X, -X, +Z, -Z and buildat's six textures are
-- the same six in the same order, so they map one to one. Fewer than six
-- copies the last one over the rest, which is what Luanti does.
--
-- What comes out is the tile *string*, texture modifiers and all: the server
-- decides which voxel types exist and the client decides what their pixels
-- are. See doc/plan/luanti_module_plan.md, "Who resolves textures".
-- Where a paletted node's colour goes in a tile's expression, if it goes in
-- at all. **Luanti applies it per layer and only to a layer that has no
-- colour of its own** -- VoxeLibre's grass block is the case that matters:
-- its side is dirt with `color = "white"` under a grass overlay with none, so
-- Luanti tints the overlay and leaves the dirt alone. The module builds one
-- expression per face in Lua and resolves the palette per slot in C++, so the
-- place is marked here and filled in there. A byte that cannot occur in a
-- texture name, the way "\1cube\1" already marks a cube in an item image.
local PALETTE_MARK = "\1pal\1"

-- What a node's own colour multiplies a tile by, as the expression tail that
-- goes where PALETTE_MARK is -- empty for a node that has a palette (the
-- palette's own colour goes there instead), no colour, or a white one.
local function node_multiply(def)
	if def == nil or def.color == nil or def.palette ~= nil then
		return ""
	end
	local c = core.colorspec_to_colorstring(def.color)
	if c == nil or c:sub(1, 7):upper() == "#FFFFFF" then
		return ""
	end
	return "^[multiply:" .. c:sub(1, 7)
end

-- A tile as the expression it is: its own colour multiplied in if it has one,
-- and otherwise a mark where the node's palette colour belongs.
local function tile_name_of(t)
	local colour = nil
	if type(t) == "table" then
		colour = t.color
		t = t.name or t.image
	end
	if type(t) ~= "string" then
		return nil
	end
	if t == "" then
		return t
	end
	if colour ~= nil then
		local c = core.colorspec_to_colorstring(colour)
		-- A tile whose own colour is white is Luanti's way of saying "not
		-- this layer" and needs no expression of its own
		if c == nil or c:sub(1, 7):upper() == "#FFFFFF" then
			return t
		end
		return t .. "^[multiply:" .. c:sub(1, 7)
	end
	return t .. PALETTE_MARK
end

-- An overlay tile is drawn over the face's own tile, and all of a node's
-- grass can be in one: devtest's dirt_with_grass is plain dirt with the
-- grass in its overlay_tiles, on purpose, so that a client which ignores
-- them shows it. The two are composed into one expression here --
-- base^(overlay) -- which is what Luanti itself does when it wants a single
-- picture of an overlaid node, in src/client/node_visuals.cpp's minimap
-- colour. Both layers are filled from the same tile context there, so a
-- node's palette colour applies to base and overlay alike and composing
-- loses no tint.
--
-- simplified: Luanti's own world draws the overlay as a second pass, with
-- its own material and a polygon offset. That matters for an overlay whose
-- animation or blending differs from its base's, and for neither of
-- devtest's; what it would take here is a second quad per face.
local function tile_names(def)
	local tiles = def and (def.tiles or def.tile_images)
	if type(tiles) ~= "table" then
		return nil
	end
	local overlays = def and def.overlay_tiles
	local out = {}
	local last = nil
	local last_overlay = nil
	for i = 1, 6 do
		local t = tile_name_of(tiles[i]) or last
		if t == nil then
			return nil
		end
		out[i] = t
		last = t
		if type(overlays) == "table" then
			-- The same last-one-repeats rule the tiles themselves take
			local o = tile_name_of(overlays[i]) or last_overlay
			if o ~= nil and o ~= "" then
				out[i] = t .. "^(" .. o .. ")"
				last_overlay = o
			end
		end
	end
	return out
end

-- The six tiles as the definition gives them, entries rather than names, so
-- that something other than the name can be read off one. Same order and
-- the same last-one-repeats rule as tile_names(), and the same swap to
-- special_tiles for a liquid.
local function six_tile_defs(def, is_liquid)
	local st = def and def.special_tiles
	if is_liquid and type(st) == "table" and tile_name_of(st[1]) ~= nil then
		local side = st[2] ~= nil and st[2] or st[1]
		return {st[1], st[1], side, side, side, side}
	end
	local tiles = def and (def.tiles or def.tile_images)
	if type(tiles) ~= "table" then
		return nil
	end
	local out = {}
	local last = nil
	for i = 1, 6 do
		if tiles[i] ~= nil then
			last = tiles[i]
		end
		out[i] = last
	end
	return out
end

-- A tile that is a strip of animation frames, as the aspect the definition
-- gives its frames -- 0 for a tile that is not one. Luanti works the frame
-- count out of the image's own proportions and this aspect, so the aspect is
-- what travels and the module, which has the file, reads the image.
--
-- simplified: only vertical_frames, which is what water, lava, fire and
-- furnaces use; a 2D sheet comes through as a still.
local function tile_frame_aspects(list)
	if type(list) ~= "table" then
		return nil
	end
	local out = {}
	local any = false
	for i = 1, 6 do
		local a = type(list[i]) == "table" and list[i].animation or nil
		local v = 0
		if type(a) == "table" and a.type == "vertical_frames" then
			local w = tonumber(a.aspect_w) or 1
			local h = tonumber(a.aspect_h) or 1
			v = (w > 0 and h > 0) and (w / h) or 1
			any = true
		end
		out[i] = v
	end
	if not any then
		return nil
	end
	return out
end

-- What the two have to come out as, checked at load against the shapes
-- VoxeLibre's own water and the devtest's own furnace give them
do
	local water = {name = "w.png", animation = {type = "vertical_frames",
			aspect_w = 16, aspect_h = 16, length = 3.0}}
	local six = six_tile_defs({special_tiles = {water}, tiles = {"t.png"}},
			true)
	assert(six[1] == water and six[6] == water,
			"a liquid's six are its special tiles")
	assert(six_tile_defs({tiles = {"t.png"}}, false)[6] == "t.png",
			"a node's own tiles repeat the last one")
	local a = tile_frame_aspects(six)
	assert(a and a[1] == 1 and a[6] == 1, "an animated tile is one of these")
	assert(tile_frame_aspects(six_tile_defs({tiles = {"plain.png"}},
			false)) == nil, "a node of still tiles carries nothing")
	local mixed = tile_frame_aspects(six_tile_defs(
			{tiles = {"plain.png", water}}, false))
	assert(mixed and mixed[1] == 0 and mixed[2] == 1 and mixed[6] == 1,
			"and the last tile is what the faces after it wear")
end

-- A liquid wears its special_tiles and not its tiles: the first is the
-- surface and the second the sides, and `tiles` is what the item looks like
-- in a hand. Same six faces in the same order as everything else.
local function liquid_tiles(def)
	local st = def and def.special_tiles
	if type(st) ~= "table" then
		return nil
	end
	local top = tile_name_of(st[1])
	if top == nil then
		return nil
	end
	local side = tile_name_of(st[2]) or top
	return {top, top, side, side, side, side}
end

