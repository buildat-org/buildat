-- Emerging an area: the map made sure of, block by block, and a callback
-- when each one is there. Luanti's emerge threads do this; here what makes
-- a section is worldgen's own thread, so what this does is ask for the
-- sections and watch the map until they answer.
--
-- The callback is Luanti's: (blockpos, action, calls_remaining, param), with
-- the actions out of constants.lua. A block outside the map's own limits is
-- EMERGE_CANCELLED, which is what a mod asking about the edge is told.
local emerge_requests = {}
-- How long a block is waited for before it is called an error. Generating a
-- section is tens of milliseconds; this is the runaway case. Not 30: with a
-- request's blocks asked for together, the last chunk of a box waits for
-- its sections behind the box's whole queue.
local EMERGE_TIMEOUT = 120

local function emerge_blockpos_list(pos1, pos2)
	local x1, y1, z1 = to_pos(pos1)
	local x2, y2, z2 = to_pos(pos2)
	local function blocks(a, b)
		local lo = math.floor(math.min(a, b) / 16)
		local hi = math.floor(math.max(a, b) / 16)
		return lo, hi
	end
	local bx1, bx2 = blocks(x1, x2)
	local by1, by2 = blocks(y1, y2)
	local bz1, bz2 = blocks(z1, z2)
	local out = {}
	for z = bz1, bz2 do
		for y = by1, by2 do
			for x = bx1, bx2 do
				-- A vector rather than a table: a mod compares the block
				-- position it is given with one of its own, and only a
				-- vector compares equal to a vector
				out[#out + 1] = vector.new(x, y, z)
			end
		end
	end
	return out
end

local function emerge_in_bounds(blockpos)
	local min_edge, max_edge = core.get_mapgen_edges()
	local lo = {x = blockpos.x * 16, y = blockpos.y * 16, z = blockpos.z * 16}
	local hi = {x = lo.x + 15, y = lo.y + 15, z = lo.z + 15}
	return lo.x >= min_edge.x and lo.y >= min_edge.y and lo.z >= min_edge.z and
			hi.x <= max_edge.x and hi.y <= max_edge.y and hi.z <= max_edge.z
end

function core.emerge_area(pos1, pos2, callback, param)
	local blocks = emerge_blockpos_list(pos1, pos2)
	if callback == nil then
		-- Nobody to tell, so this is only "have these, please"
		for _, bp in ipairs(blocks) do
			if emerge_in_bounds(bp) then
				core.__forceload_block_raw(bp)
			end
		end
		return
	end
	emerge_requests[#emerge_requests + 1] = {
		blocks = blocks,
		next_i = 1,
		asked = false,
		waited = 0,
		callback = callback,
		param = param,
		-- Who asked, for the slow-step line: the mod loading, or the one
		-- that last ran
		mod = core.get_current_modname() or core.get_last_run_mod() or "?",
	}
end

-- Luanti loads the area and returns once it is there; nothing here can wait
-- for another thread, and a write into a section that is not loaded emerges
-- it anyway (see flush_node_writes in luanti.cpp), so this asks and returns.
function core.load_area(pos1, pos2)
	core.emerge_area(pos1, pos2 or pos1, nil, nil)
end

-- Where the emerge phase's time went this step, for the slow-step line:
-- the one read for every request (a flush and a commit) against the
-- callbacks, which are the mapgen mods' structure placers
local emerge_detail = {ids = 0, asked = 0, callbacks = 0, n_callbacks = 0,
		worst = 0, worst_mod = ""}
core.__emerge_detail = emerge_detail

-- How much of a step the callbacks may take. They are the emerge phase:
-- a section arriving turns every request waiting on a block of it
-- generated at once, and eighteen hundred callbacks of a structure
-- placer each were 7 to 11 s of one step with a player walking a fresh
-- VoxeLibre world (the fuzz run, 2026-09-17). Luanti spreads them over
-- the steps its emerge thread delivers blocks in; this cuts the slice
-- and leaves the rest for the next step. See [STEP_PEAK].
local EMERGE_BUDGET_US = 50000

-- How many blocks ahead of the one a request is on are asked for. One at
-- a time, a box's sections were generated one after another, a block a
-- step; Luanti asks for all of a request's blocks at once.
local EMERGE_WINDOW = 32

local function step_emerge(dtime)
	-- Which of each waiting request's next blocks are there, asked all at
	-- once. This used to be a core.get_node() per request per step, and a
	-- read that crosses the Lua boundary costs a module lock and its
	-- hierarchy validated -- with a mapgen's worth of requests outstanding
	-- that was up to two seconds of a step. The work inside voxelworld is
	-- nearly free beside the crossing, so one crossing for the lot is the
	-- whole fix.
	local ask = {}
	local ask_of = {}
	for i = 1, #emerge_requests do
		local r = emerge_requests[i]
		ask_of[r] = #ask / 3 + 1
		-- What was asked for before this step is what voxelworld has been
		-- told to keep: a forceload reaches it with the next push of the
		-- load points, and a block asked for now can be unloaded under
		-- the read in between
		r.kept_upto = r.asked_upto or 0
		for j = r.next_i, math.min(#r.blocks, r.next_i + EMERGE_WINDOW - 1) do
			local bp = r.blocks[j]
			if emerge_in_bounds(bp) then
				-- Asked once and kept until its callback has run
				if (r.asked_upto or r.next_i - 1) < j then
					r.asked_upto = j
					core.__forceload_block_raw(bp)
				end
			end
			ask[#ask + 1] = bp.x * 16
			ask[#ask + 1] = bp.y * 16
			ask[#ask + 1] = bp.z * 16
		end
	end
	local t_ids = core.get_us_time()
	-- Whether the block's section is there, per block: what "generated"
	-- means here, since an ungenerated section reads as ignore everywhere
	local ids = #ask > 0 and __luanti_loaded_at(ask) or {}
	emerge_detail.ids = emerge_detail.ids + (core.get_us_time() - t_ids)
	emerge_detail.asked = emerge_detail.asked + #ask / 3

	local t_start = core.get_us_time()
	local i = 1
	while i <= #emerge_requests do
		if core.get_us_time() - t_start > EMERGE_BUDGET_US then
			break
		end
		local r = emerge_requests[i]
		r.waited = r.waited + dtime
		-- The blocks in order, as many as are there and the budget allows
		local at = ask_of[r]
		local first = r.next_i
		while r.next_i <= #r.blocks and
				r.next_i < first + EMERGE_WINDOW and
				(r.next_i <= r.kept_upto or
				not emerge_in_bounds(r.blocks[r.next_i])) do
			if core.get_us_time() - t_start > EMERGE_BUDGET_US then
				break
			end
			local bp = r.blocks[r.next_i]
			local action = nil
			if not emerge_in_bounds(bp) then
				action = core.EMERGE_CANCELLED
			elseif at ~= nil and ids[at + r.next_i - first] then
				action = core.EMERGE_GENERATED
			elseif r.waited > EMERGE_TIMEOUT then
				action = core.EMERGE_ERRORED
			end
			if action == nil then
				break
			end
			if emerge_in_bounds(bp) and (r.asked_upto or 0) >= r.next_i then
				core.__forceload_free_block_raw(bp)
			end
			r.waited = 0
			r.next_i = r.next_i + 1
			local left = #r.blocks - r.next_i + 1
			local t_cb = core.get_us_time()
			core.set_last_run_mod(r.mod)
			-- With a traceback: a mapgen mod's callback that fails names
			-- a line in vector.lua otherwise, and which mod is the question
			local ok, err = xpcall(function()
				return r.callback(bp, action, left, r.param)
			end, debug.traceback)
			local took = core.get_us_time() - t_cb
			emerge_detail.callbacks = emerge_detail.callbacks + took
			emerge_detail.n_callbacks = emerge_detail.n_callbacks + 1
			if took > emerge_detail.worst then
				-- Named by where the callback was written, since the mod
				-- that asked is often mcl_mapgen_core on behalf of another
				local info = debug.getinfo(r.callback, "S")
				emerge_detail.worst = took
				emerge_detail.worst_mod = r.mod .. " (" ..
						(info and (info.short_src .. ":" ..
						tostring(info.linedefined)) or "?") .. ")"
			end
			if not ok then
				core.log("error", "emerge_area callback: " .. tostring(err))
			end
		end
		if r.next_i > #r.blocks then
			table.remove(emerge_requests, i)
		else
			i = i + 1
		end
	end
end

core.__step_emerge = step_emerge

function core.get_meta(pos)
	local x, y, z = to_pos(pos)
	local key = pos_key(x, y, z)
	local meta = node_meta[key]
	if meta == nil then
		meta = core.__new_metadata({})
		-- A node's metadata carries an inventory and an item stack's does
		-- not, which is the whole difference between the two in Luanti as
		-- well: a chest is a list in here
		meta.inventory = core.__new_inventory(
				{type = "node", pos = {x = x, y = y, z = z}})
		-- Where it is, so that the section it belongs to can be worked out
		-- without taking the key apart again; see core.__take_node_meta()
		meta.pos = {x = x, y = y, z = z}
		node_meta[key] = meta
	end
	return meta
end

