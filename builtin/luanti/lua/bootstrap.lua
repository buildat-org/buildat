end

-- The light voxelworld propagates, which the voxel word carries in the same
-- bits Luanti's param1 does. Time of day is M2's clock; until it is there,
-- the sky is at full strength.
-- The light readers land the write buffer first: a get_node() answers
-- out of the buffer without it, and the light a placed lamp floods
-- into its neighbours is only in the world once the buffer has
-- landed. See read_node() in luanti.cpp.
function core.get_natural_light(pos, timeofday)
	local x, y, z = to_pos(pos)
	__luanti_flush_node_writes()
	local _, param1 = __get_node(x, y, z)
	return math.floor(param1 % 16)
end

function core.get_artificial_light(param1)
	return math.floor(param1 / 16) % 16
end

-- **The hour is read, not ignored.** Luanti turns the argument into a
-- day-night ratio and blends the two nibbles by it -- blend_light() in
-- light.h, over getLightBlend() -- so get_node_light(pos, 0) asks *what light
-- reaches here from something other than the sun*, and the answer outdoors is
-- zero. Answering max(day, night) instead said 15 there, and VoxeLibre's
-- melting ABM takes that as sunlight and deletes every snow slab it can see:
-- the snow field thinned as a run went on. Water freezing and mob spawning
-- ask the same question. See [NODE_LIGHT_HOUR] in
-- doc/plan/luanti_module_plan.md.
--
-- No hour means the world's own, which is what Luanti does with it.
function core.get_node_light(pos, timeofday)
	local x, y, z = to_pos(pos)
	__luanti_flush_node_writes()
	local id, param1 = __get_node(x, y, z)
	if id == core.CONTENT_IGNORE then
		return nil
	end
	local sky = math.floor(param1 % 16)
	local lamp = math.floor(param1 / 16) % 16
	local t = tonumber(timeofday)
	if t == nil then
		t = core.get_timeofday()
	end
	-- voxelworld's two fields are not Luanti's two banks: the sky field is
	-- sunlight alone, where Luanti's day bank is whichever of sunlight and
	-- lamplight is stronger -- light sources seed the lamp field only, see
	-- set_voxel() in voxelworld.cpp. So the day bank is built here. Blending
	-- the fields as they are would put a lit room in the dark at noon.
	local day = sky > lamp and sky or lamp
	-- 0...1000, the way the C++ carries it, so the arithmetic below is
	-- Luanti's own rather than a rounding of it
	local dnr = math.floor(core.time_to_day_night_ratio(t) * 1000 + 0.5)
	return core.blend_light(dnr, day, lamp)
end

-- The region reads: the same seam over a box instead of a voxel.
--
-- simplified: a voxel at a time through the same two C functions, so a big
-- box is a lot of small reads. The upgrade path is one C call that reads a
-- region out of voxelworld, which is what VoxelManip wants anyway; the
-- shapes of these functions do not change when it arrives.

local function name_matcher(nodenames)
	if type(nodenames) == "string" then
		nodenames = {nodenames}
	end
	local plain = {}
	local groups = {}
	for _, n in ipairs(nodenames) do
		local g = string.match(n, "^group:(.*)$")
		if g then
			groups[#groups + 1] = g
		else
			plain[n] = true
			-- An old name a game keeps as an alias means the node it
			-- names, as Luanti's getIds() resolves it ([FEATURE_SWEEP_1009])
			local a = core.__aliases[n]
			if a then
				plain[a] = true
			end
		end
	end
	-- What each name answered, because this is asked once per voxel of a box
	-- and a box is a handful of distinct nodes however large it is. A
	-- matcher is made per call, so nothing here outlives the question it is
	-- about and a mod registering an item cannot be answered stale.
	--
	-- VoxeLibre's world generation had 30% of its Lua in this function and
	-- another 20% in get_item_group() underneath it.
	local answered = {}
	return function(name)
		local was = answered[name]
		if was ~= nil then
			return was
		end
		local yes = false
		if plain[name] then
			yes = true
		else
			for _, g in ipairs(groups) do
				if core.get_item_group(name, g) ~= 0 then
					yes = true
					break
				end
			end
		end
		answered[name] = yes
		return yes
	end
end

-- The box read the three functions below share: one engine call rather than
-- one per voxel, since a read that crosses the Lua boundary costs a module
-- lock and its hierarchy validated, and the work inside voxelworld is nearly
-- free by comparison. The array is x fastest and then y and then z.
--
-- The name lookup is cached per content id, because a box is usually a
-- handful of distinct nodes however large it is.
local function region_names(x0, y0, z0, x1, y1, z1)
	local ids = __get_region(x0, y0, z0, x1, y1, z1)
	local names = {}
	local name_of = {}
	for i = 1, #ids do
		local id = ids[i]
		local name = name_of[id]
		if name == nil then
			name = core.get_name_from_content_id(id)
			name_of[id] = name
		end
		names[i] = name
	end
	return names
end

-- The same question asked of a content id instead of a name, which is what
-- the region reads have in hand: a box is a handful of distinct ids however
-- large it is, so the name is looked up once per id and the answer kept.
-- What a caller gets is two functions over the same two tables -- does this
-- id match, and what is it called.
-- One matcher per name list, kept. core.find_node_near() builds one per
-- call and an ABM asks it about every candidate node it has -- the neighbour
-- test is a find_node_near -- so this was 15% of all the Lua a VoxeLibre
-- world spent generating, in name_matcher()'s inner function, building the
-- same tables over and over. Keeping the matcher keeps its memo too, which
-- is the point of having one. core.__forget_name_ids() drops them, which is
-- what a node registered after load needs.
local matcher_cache = {}

local function matcher_key(nodenames)
	if type(nodenames) == "string" then
		return nodenames
	end
	return table.concat(nodenames, "\1")
end

local function id_matcher(nodenames)
	local key = matcher_key(nodenames)
	local have = matcher_cache[key]
	if have ~= nil then
		return have[1], have[2], have[3]
	end
	local matches = name_matcher(nodenames)
	local name_of = {}
	local hit = {}
	local function name_of_id(id)
		local name = name_of[id]
		if name == nil then
			name = core.get_name_from_content_id(id)
			name_of[id] = name
		end
		return name
	end
	local function matches_id(id)
		-- Outside the box is nothing rather than an error, which is what a
		-- name matcher answered when it was handed a nil name
		if id == nil then
			return false
		end
		local was = hit[id]
		if was == nil then
			was = matches(name_of_id(id))
			hit[id] = was
		end
		return was
	end
	-- The memo is handed out as well, for a caller hot enough to want the
	-- table lookup without the call around it: `hit[id]` is true, false, or
	-- nil for an id nobody has asked about yet, and matches_id() is what
	-- answers that last case. See core.find_node_near().
	matcher_cache[key] = {matches_id, name_of_id, hit}
	return matches_id, name_of_id, hit
end

-- Which content ids a name list is about, and the name of each, kept because
-- working it out walks every node the game registered -- two and a half
-- thousand of them in VoxeLibre -- and the answer cannot change: the node
-- registry is frozen once the mods have loaded.
local ids_for_names = {}

-- Called when an item is registered; see core.register_item_raw()
function core.__forget_name_ids()
	ids_for_names = {}
	matcher_cache = {}
	-- The id sets an ABM and an LBM sweep with are the same answer to the
	-- same question and go stale in the same breath. They live further down
	-- with the sweep, so this asks rather than reaches.
	if core.__forget_sweep_ids then
		core.__forget_sweep_ids()
	end
end

local function ids_and_names(nodenames)
	local key = type(nodenames) == "string" and nodenames or
			table.concat(nodenames, "\1")
	local have = ids_for_names[key]
	if have ~= nil then
		return have[1], have[2]
	end
	local matches = name_matcher(nodenames)
	local ids = {}
	local name_of = {}
	for name, _ in pairs(core.registered_nodes) do
		if matches(name) then
			local id = core.get_content_id(name)
			ids[#ids + 1] = id
			name_of[id] = name
		end
	end
	ids_for_names[key] = {ids, name_of}
	return ids, name_of
end

-- Where the ground is at a point, which is what a player who has never been
-- here starts on top of. nil means nobody can stand here.
--
-- Luanti asks two things in this order and so does this: first the mapgen,
-- which answers out of its own noise for a part of the world nobody has
-- generated -- Server::findSpawnPos() does that because at the moment a
-- player joins the map around the origin is half made, and a map read then
-- answers about the world as it was rather than as it will be -- and then
-- the map, for the two nodes of room a player needs. A mapgen that says
-- "not here" (a river, or a surface under water) is not argued with.
local SPAWN_SCAN_BOTTOM = -256
local SPAWN_SCAN_TOP = 320
-- How much room a player needs above the ground to stand in it
local SPAWN_HEADROOM = 2
-- How far above the mapgen's answer to look for that room, which is
-- Luanti's own number
local SPAWN_SEARCH_UP = 8

-- What a player can be inside: air, anything a game made unwalkable, and
-- ignore -- because an ungenerated part of the world has no obstruction in
-- it, which is Luanti's reasoning and what lets a spawn be chosen before
-- the ground below it exists.
local function is_empty_for_spawn(name)
	if name == "air" or name == "ignore" then
		return true
	end
	local def = core.registered_nodes[name]
	if def == nil then
		return false
	end
	return def.walkable == false or def.drawtype == "airlike"
end

-- The map's own answer: from y upwards, the first place with room for a
-- player, standing in the lower of the empty nodes. nil if the column has
-- no such place in reach.
local function spawn_level_in_map(x, y, z, up)
	local names = region_names(x, y, z, x, y + up, z)
	local room = 0
	for i = 1, #names do
		if is_empty_for_spawn(names[i]) then
			room = room + 1
			if room >= SPAWN_HEADROOM then
				-- The lower of the two: index i is at y + i - 1
				return y + i - SPAWN_HEADROOM
			end
		else
			room = 0
		end
	end
	return nil
end

-- The map's answer for a whole column: the surface, walked from the top so
-- that what is found is the ground and not the roof of the first cave. nil
-- if the column has no ground in it, which for an ungenerated column is
-- what it always says.
local function spawn_level_in_column(x, z)
	local names = region_names(x, SPAWN_SCAN_BOTTOM, z, x, SPAWN_SCAN_TOP, z)
	local room = 0
	for i = #names, 1, -1 do
		local name = names[i]
		local def = core.registered_nodes[name]
		if name == "ignore" or def == nil then
			-- Not generated, so nothing can be said about what is under it
			room = 0
		elseif def.walkable == false or name == "air" then
			room = room + 1
		else
			if room >= SPAWN_HEADROOM then
				-- The voxel above this one: index i is at
				-- SPAWN_SCAN_BOTTOM + i - 1, so this is standing on it
				return SPAWN_SCAN_BOTTOM + i
			end
			room = 0
		end
	end
	return nil
end

-- Where a player can stand above (x, z), or nil.
--
-- deep says whether the map's whole column may be walked when the mapgen's
-- answer does not match it. That walk is six hundred voxels of map read, so
-- the spawn search asks for it at a handful of points rather than at the
-- thousands it tries -- see find_spawn_pos() in lua/entity.lua.
function core.get_spawn_level(x, z, deep)
	x, z = math.floor(x + 0.5), math.floor(z + 0.5)
	local from_mapgen = __luanti_spawn_level and __luanti_spawn_level(x, z)
	if from_mapgen then
		local level = spawn_level_in_map(x, from_mapgen, z, SPAWN_SEARCH_UP)
		if level then
			return level
		end
		if not deep then
			return nil
		end
		-- The mapgen said where its own terrain is and the map does not
		-- agree. A game that builds its world in core.register_on_generated
		-- over what the mapgen made -- VoxeLibre does, and its ground can be
		-- tens of nodes from v7's -- is that case, so the column itself is
		-- asked. An ungenerated column answers nil and the search comes back
		-- to it once there is something there.
		return spawn_level_in_column(x, z)
	end
	if core.__mapgen_name() ~= "singlenode" then
		-- There is a mapgen and it said "not here", which is its answer to
		-- give: a river, or a surface under water
		return nil
	end
	-- No mapgen to ask -- a singlenode world, whose ground is whatever a
	-- mod built
	return spawn_level_in_column(x, z)
end

-- Luanti sorts by distance and returns the nearest; search_center adds pos
-- itself as the first thing looked at
function core.find_node_near(pos, radius, nodenames, search_center)
	-- The memo beside the matcher: this loop asks about the same few ids
	-- tens of thousands of times, so the answer is a table lookup and the
	-- call is only for an id this list has not seen before.
	local matches, _, hit = id_matcher(nodenames)
	local x, y, z = to_pos(pos)
	local ids = __get_region(x - radius, y - radius, z - radius,
			x + radius, y + radius, z + radius)
	local w = radius * 2 + 1
	local w2 = w * w
	-- ids is a flat (2r+1)^3 box and this is where its middle is, so a cell
	-- is an add and two multiplies away. Written out rather than reached
	-- through a closure because a call per voxel was half of this
	-- function's time in a profile of realtest's generation.
	local mid = radius + radius * w + radius * w2 + 1
	local id = ids[mid]
	if search_center and (hit[id] or (hit[id] == nil and matches(id))) then
		return {x = x, y = y, z = z}
	end
	-- Shells outwards, so the first hit is the nearest one.
	--
	-- **The shell is walked as a shell.** Filtering a whole cube for the
	-- cells on its surface is r^3 work for r^2 of them, and at radius ten
	-- that is eighty-eight thousand iterations where nine thousand will do.
	-- A mapgen calls this per ore and per decoration, and it was 87% of the
	-- server's Lua time in realtest's generation before this.
	--
	-- A row is on the surface when it is on the x or the y face -- then the
	-- whole row is -- and otherwise only its two ends are.
	for r = 1, radius do
		local rw2 = r * w2
		for dx = -r, r do
			local edge_x = (dx == -r or dx == r)
			local ix = mid + dx
			for dy = -r, r do
				local ixy = ix + dy * w
				if edge_x or dy == -r or dy == r then
					for dz = -r, r do
						id = ids[ixy + dz * w2]
						if hit[id] or
								(hit[id] == nil and matches(id)) then
							return {x = x + dx, y = y + dy, z = z + dz}
						end
					end
				else
					id = ids[ixy - rw2]
					if hit[id] or (hit[id] == nil and matches(id)) then
						return {x = x + dx, y = y + dy, z = z - r}
					end
					id = ids[ixy + rw2]
					if hit[id] or (hit[id] == nil and matches(id)) then
						return {x = x + dx, y = y + dy, z = z + r}
					end
				end
			end
		end
	end
	return nil
end

-- That the walk above visits exactly the cells the cube-and-filter walk it
-- replaces visited, **in the same order**: the same set in another order
-- still finds a nearest node, but not the same one, and which of several
-- equally near nodes is answered is part of what a game is built on. The
-- old walk is written out again here because that is what is being checked
-- against; it is a reference and not a second implementation.
do
	local function walked(radius, shell)
		local out = {}
		for r = 1, radius do
			for dx = -r, r do
				local edge_x = (dx == -r or dx == r)
				for dy = -r, r do
					if not shell then
						for dz = -r, r do
							if math.max(math.abs(dx), math.abs(dy),
									math.abs(dz)) == r then
								out[#out + 1] = dx .. "," .. dy .. "," .. dz
							end
						end
					elseif edge_x or dy == -r or dy == r then
						for dz = -r, r do
							out[#out + 1] = dx .. "," .. dy .. "," .. dz
						end
					else
						out[#out + 1] = dx .. "," .. dy .. "," .. (-r)
						out[#out + 1] = dx .. "," .. dy .. "," .. r
					end
				end
			end
		end
		return out
	end
	local old, new = walked(3, false), walked(3, true)
	assert(#old == #new, "the shell walk visits as many cells: " ..
			#old .. " against " .. #new)
	for i = 1, #old do
		assert(old[i] == new[i], "and the same one in the same place, at " ..
				i .. ": " .. old[i] .. " against " .. new[i])
	end
end

